package cmd

import (
	"bufio"
	"fmt"
	"os"
	"strings"

	"github.com/david22573/codepicker/internal/shadow"
	"github.com/spf13/cobra"
)

var autoApprove bool

var applyCmd = &cobra.Command{
	Use:   "apply",
	Short: "Review and apply changes from the shadow filesystem",
	Long:  `Iterates through files generated by the agent in the shadow directory (.codepicker/shadow). Shows a diff for each file and asks for confirmation before overwriting source files.`,
	RunE: func(cmd *cobra.Command, args []string) error {
		// Initialize shadow manager using the global srcDir
		sm, err := shadow.NewManager(srcDir)
		if err != nil {
			return fmt.Errorf("failed to init shadow manager: %w", err)
		}

		files, err := sm.ListShadowFiles()
		if err != nil {
			return fmt.Errorf("failed to list shadow files: %w", err)
		}

		if len(files) == 0 {
			fmt.Println("✨ No pending changes in shadow directory.")
			return nil
		}

		fmt.Printf("📦 Found %d pending change(s):\n", len(files))
		scanner := bufio.NewScanner(os.Stdin)

		for i, file := range files {
			fmt.Printf("\n[%d/%d] Reviewing: %s\n", i+1, len(files), file)

			diff, err := sm.PreviewDiff(file)
			if err != nil {
				appLogger.Warn(fmt.Sprintf("Could not generate diff for %s: %v", file, err))
				continue
			}

			fmt.Println(strings.Repeat("-", 60))
			fmt.Println(diff)
			fmt.Println(strings.Repeat("-", 60))

			if autoApprove {
				if err := applyChange(sm, file); err != nil {
					appLogger.Error(fmt.Sprintf("Failed to apply %s: %v", file, err))
				}
				continue
			}

			fmt.Print("👉 Apply this change? [y=Yes, n=No, a=All, q=Quit]: ")
			if !scanner.Scan() {
				break
			}
			input := strings.ToLower(strings.TrimSpace(scanner.Text()))

			switch input {
			case "y", "yes":
				if err := applyChange(sm, file); err != nil {
					appLogger.Error(fmt.Sprintf("Failed to apply %s: %v", file, err))
				}
			case "a", "all":
				autoApprove = true
				if err := applyChange(sm, file); err != nil {
					appLogger.Error(fmt.Sprintf("Failed to apply %s: %v", file, err))
				}
				fmt.Println("   (Auto-approving remaining files...)")
			case "q", "quit":
				fmt.Println("👋 Aborting review.")
				return nil
			case "n", "no":
				fmt.Println("   Skipped.")
			default:
				fmt.Println("   Skipped (invalid input).")
			}
		}

		// Optional: Offer to clean up shadow dir after applying
		if !autoApprove {
			fmt.Print("\n🧹 Clear shadow directory? [y/N]: ")
			if scanner.Scan() {
				if strings.ToLower(strings.TrimSpace(scanner.Text())) == "y" {
					sm.Cleanup()
					fmt.Println("✨ Shadow directory cleaned.")
				}
			}
		} else {
			sm.Cleanup()
			fmt.Println("✨ Shadow directory cleaned.")
		}

		return nil
	},
}

func applyChange(sm *shadow.Manager, file string) error {
	if err := sm.Apply(file); err != nil {
		return err
	}
	fmt.Printf("✅ Applied: %s\n", file)
	return nil
}

func init() {
	rootCmd.AddCommand(applyCmd)
	applyCmd.Flags().BoolVarP(&autoApprove, "yes", "y", false, "Automatically apply all changes without prompting")
}
