func TestCalculateRecencyScore(t *testing.T) {
	now := time.Now()

	tests := []struct {
		name          string
		lastAccessed  time.Time
		expectedRange [2]float64 // min, max
		description   string
	}{
		{
			name:          "Very Recent (30s ago)",
			lastAccessed:  now.Add(-30 * time.Second),
			expectedRange: [2]float64{0.95, 1.0},
			description:   "Should be near maximum",
		},
		{
			name:          "Recent (5 min ago)",
			lastAccessed:  now.Add(-5 * time.Minute),
			expectedRange: [2]float64{0.6, 0.8},
			description:   "Should be high but declining",
		},
		{
			name:          "Moderate (20 min ago)",
			lastAccessed:  now.Add(-20 * time.Minute),
			expectedRange: [2]float64{0.2, 0.4},
			description:   "Should be moderate",
		},
		{
			name:          "Old (2 hours ago)",
			lastAccessed:  now.Add(-2 * time.Hour),
			expectedRange: [2]float64{0.0, 0.1},
			description:   "Should be very low",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			score := calculateRecencyScore(tt.lastAccessed, now)

			if score < tt.expectedRange[0] || score > tt.expectedRange[1] {
				t.Errorf("%s: got %.3f, want between %.3f and %.3f",
					tt.description, score, tt.expectedRange[0], tt.expectedRange[1])
			}
		})
	}
}

