func TestCalculateImportanceScore(t *testing.T) {
	tests := []struct {
		name          string
		path          string
		content       string
		expectedRange [2]float64
		description   string
	}{
		{
			name:          "go.mod (critical)",
			path:          "go.mod",
			content:       "module example.com/test",
			expectedRange: [2]float64{1.0, 1.0},
			description:   "Should be maximum importance",
		},
		{
			name:          "main.go (core)",
			path:          "cmd/main.go",
			content:       "package main\nfunc main() {}",
			expectedRange: [2]float64{0.7, 0.9},
			description:   "Main files are important",
		},
		{
			name:          "schema.go (core infrastructure)",
			path:          "internal/database/schema.go",
			content:       "package database",
			expectedRange: [2]float64{0.6, 0.8},
			description:   "Schema files are important",
		},
		{
			name:          "types.go (interfaces)",
			path:          "internal/types.go",
			content:       "package internal\ntype MyInterface interface{}",
			expectedRange: [2]float64{0.6, 0.8},
			description:   "Type definitions matter",
		},
		{
			name:          "test file",
			path:          "internal/database/store_test.go",
			content:       "package database\nfunc TestStore(t *testing.T) {}",
			expectedRange: [2]float64{0.2, 0.4},
			description:   "Tests are less critical",
		},
		{
			name:          "generated file",
			path:          "internal/generated/models.go",
			content:       "// Code generated by protoc-gen-go",
			expectedRange: [2]float64{0.1, 0.3},
			description:   "Generated files are low priority",
		},
		{
			name:          "vendor file",
			path:          "vendor/github.com/some/package/file.go",
			content:       "package something",
			expectedRange: [2]float64{0.0, 0.2},
			description:   "Vendor files are very low priority",
		},
		{
			name:          "deeply nested utility",
			path:          "internal/utils/helpers/formatting/string/trim.go",
			content:       "package string",
			expectedRange: [2]float64{0.2, 0.4},
			description:   "Deep nesting reduces importance",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			score := calculateImportanceScore(tt.path, tt.content)

			if score < tt.expectedRange[0] || score > tt.expectedRange[1] {
				t.Errorf("%s: path=%s got %.3f, want between %.3f and %.3f",
					tt.description, tt.path, score, tt.expectedRange[0], tt.expectedRange[1])
			}
		})
	}
}

func TestCalculateRelationshipScore(t *testing.T) {
	file1 := RelevanceScore{
		Path:    "internal/database/store.go",
		Content: `package database\nimport "internal/tokenizer"\nfunc (s *Store) DoSomething() {}`,
	}

	file2 := RelevanceScore{
		Path:    "internal/tokenizer/tokenizer.go",
		Content: `package tokenizer\nfunc CountTokens(s string) int { return 0 }`,
	}

	file3 := RelevanceScore{
		Path:    "cmd/main.go",
		Content: `package main\nimport "internal/database"\nfunc main() { store := database.New() }`,
	}

	allFiles := []RelevanceScore{file1, file2, file3}

	tests := []struct {
		name        string
		file        *RelevanceScore
		minExpected float64
		description string
	}{
		{
			name:        "store.go (references tokenizer)",
			file:        &file1,
			minExpected: 0.1,
			description: "Should have some relationships",
		},
		{
			name:        "main.go (references database)",
			file:        &file3,
			minExpected: 0.1,
			description: "Should have some relationships",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			score := calculateRelationshipScore(tt.file, allFiles)

			if score < tt.minExpected {
				t.Errorf("%s: got %.3f, expected at least %.3f",
					tt.description, score, tt.minExpected)
			}
		})
	}
}

func TestCalculateFinalScore(t *testing.T) {
	tests := []struct {
		name string
		rs   RelevanceScore
	}{
		{
			name: "High relevance file",
			rs: RelevanceScore{
				RecencyScore:      0.9,
				FrequencyScore:    0.8,
				ImportanceScore:   1.0,
				RelationshipScore: 0.7,
			},
		},
		{
			name: "Low relevance file",
			rs: RelevanceScore{
				RecencyScore:      0.1,
				FrequencyScore:    0.2,
				ImportanceScore:   0.3,
				RelationshipScore: 0.0,
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			score := calculateFinalScore(&tt.rs)

			// Score should be between 0 and 1
			if score < 0.0 || score > 1.0 {
				t.Errorf("Final score %.3f is out of range [0.0, 1.0]", score)
			}

			// Score should be a weighted average, roughly
			expectedMin := (0.35 * tt.rs.RecencyScore) + (0.20 * tt.rs.FrequencyScore) +
				(0.30 * tt.rs.ImportanceScore) + (0.15 * tt.rs.RelationshipScore)

			if score < expectedMin-0.01 || score > expectedMin+0.01 {
				t.Errorf("Final score %.3f doesn't match expected %.3f", score, expectedMin)
			}
		})
	}
}

